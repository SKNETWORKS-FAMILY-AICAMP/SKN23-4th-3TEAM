# 브릿지 매핑: (1위 키워드, 2위 키워드) → 브릿지 타입 키
BRIDGE_MAP = {
    ("봄 라이트", "봄 브라이트"): "봄 라이트+봄 브라이트",
    ("봄 브라이트", "봄 라이트"): "봄 라이트+봄 브라이트",
    ("여름 라이트", "여름 뮤트"): "여름 라이트+여름 뮤트",
    ("여름 뮤트", "여름 라이트"): "여름 라이트+여름 뮤트",
    ("가을 뮤트", "가을 딥"): "가을 뮤트+가을 딥",
    ("가을 딥", "가을 뮤트"): "가을 뮤트+가을 딥",
    ("겨울 브라이트", "겨울 딥"): "겨울 브라이트+겨울 딥",
    ("겨울 딥", "겨울 브라이트"): "겨울 브라이트+겨울 딥",
    ("봄 라이트", "여름 라이트"): "봄 라이트+여름 라이트",
    ("여름 라이트", "봄 라이트"): "봄 라이트+여름 라이트",
    ("여름 뮤트", "가을 뮤트"): "여름 뮤트+가을 뮤트",
    ("가을 뮤트", "여름 뮤트"): "여름 뮤트+가을 뮤트",
}


def determine_type(scores: dict) -> dict:
    """
    GPT가 산출한 점수 dict를 받아서 14타입 중 하나를 확정한다.
    scores: {"봄 라이트": 60, "봄 브라이트": 30, "여름 라이트": 10, ...}
    반환: PERSONAL_COLOR_TYPES의 해당 타입 dict + "type_key" 추가
    """
    sorted_scores = sorted(scores.items(), key=lambda x: x[1], reverse=True)
    first_key, first_score = sorted_scores[0]
    second_key, second_score = sorted_scores[1] if len(sorted_scores) > 1 else ("", 0)

    # 1위가 70점 이상이면 기본 타입 확정
    if first_score >= 70:
        type_key = first_key
    else:
        # 브릿지 타입 매칭 시도
        bridge_key = BRIDGE_MAP.get((first_key, second_key))
        if bridge_key:
            type_key = bridge_key
        else:
            # 브릿지 조합이 정의되지 않은 경우 1위 타입으로 확정
            type_key = first_key

    type_data = PERSONAL_COLOR_TYPES.get(type_key, PERSONAL_COLOR_TYPES[first_key])
    return {**type_data, "type_key": type_key, "scores": scores}


